"""Run the trained TESA Day 1 coffee classifier on a Raspberry Pi CPU."""
import argparse
import csv
import shutil
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

from PIL import Image, ImageOps

CLASSES = ("good", "shell", "black", "husk", "broken", "parchment", "immature")
EXTENSIONS = {".jpg", ".jpeg", ".png"}
IMAGE_SIZE = 320


def prepare_image(path, size):
    """Apply EXIF orientation, then fit the entire frame into a square."""
    with Image.open(path) as raw:
        rgb = ImageOps.exif_transpose(raw).convert("RGB")
        return ImageOps.pad(
            rgb, (size, size), method=Image.Resampling.BILINEAR, color=(220, 220, 220)
        )


def load_model(weights):
    if not weights.is_dir():
        raise FileNotFoundError(f"Weights directory not found: {weights}")
    model_path = weights / "best.pt"
    if not model_path.is_file():
        candidates = sorted(p for p in weights.iterdir() if p.is_file() and p.suffix.lower() == ".pt")
        if not candidates:
            raise FileNotFoundError(f"No PyTorch checkpoint found in {weights}")
        if len(candidates) != 1:
            raise ValueError(f"Multiple checkpoints found in {weights}. Name the submitted one best.pt.")
        model_path = candidates[0]

    from ultralytics import YOLO

    model = YOLO(str(model_path))
    if model.task != "classify":
        raise ValueError("Weights must be from a classification model.")
    names = model.names
    classes = list(names.values()) if isinstance(names, dict) else list(names)
    if len(classes) != len(CLASSES) or set(classes) != set(CLASSES):
        raise ValueError("Weights must provide the seven Day 1 classes.")
    return model


def predict_image(model, source):
    (result,) = model.predict(
        source=prepare_image(source, IMAGE_SIZE),
        imgsz=IMAGE_SIZE,
        device="cpu",
        half=False,
        augment=False,
        verbose=False,
    )
    if result.probs is None or result.probs.data.shape != (len(CLASSES),):
        raise ValueError(f"Invalid classification output for {source}")
    label = result.names[result.probs.top1]
    if label not in CLASSES:
        raise ValueError(f"Unexpected class {label!r} for {source}")
    return label


def input_images(path):
    if path.is_file():
        candidates = [path]
    elif path.is_dir():
        candidates = list(path.rglob("*"))
    else:
        raise FileNotFoundError(f"Input not found: {path}")

    images = sorted(p for p in candidates if p.is_file() and p.suffix.lower() in EXTENSIONS)
    if not images:
        raise ValueError(f"No jpg, jpeg, or png images found: {path}")
    if len({p.name.casefold() for p in images}) != len(images):
        raise ValueError("Input image filenames must be unique.")
    return images


def write_outputs(results, output):
    output.parent.mkdir(parents=True, exist_ok=True)
    # Stage a complete run before replacing files generated by an earlier run.
    with TemporaryDirectory(prefix=".day1-", dir=output.parent) as temp:
        stage = Path(temp) / "new"
        stage.mkdir()
        for label in CLASSES:
            (stage / label).mkdir()
        with (stage / "predictions.csv").open("w", encoding="utf-8", newline="") as stream:
            writer = csv.writer(stream)
            writer.writerow(("filename", "class"))
            for source, label in results:
                shutil.copy2(source, stage / label / source.name)
                writer.writerow((source.name, label))

        previous = Path(temp) / "previous"
        if output.exists():
            if not output.is_dir():
                raise ValueError(f"Output path must be a directory: {output}")
            allowed = {output / label for label in CLASSES}
            csv_path = output / "predictions.csv"
            if csv_path.is_file():
                allowed.add(csv_path)
                with csv_path.open(encoding="utf-8", newline="") as stream:
                    for row in csv.DictReader(stream):
                        label, filename = row["class"], row["filename"]
                        if label in CLASSES and Path(filename).name == filename:
                            allowed.add(output / label / filename)
            if set(output.rglob("*")) - allowed:
                raise ValueError(f"Output contains other files. Use a dedicated directory: {output}")
            output.rename(previous)
        try:
            stage.rename(output)
        except OSError:
            if previous.exists():
                previous.rename(output)
            raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--weights", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    source, output = args.input.resolve(), args.out.resolve()
    weights = args.weights.resolve()
    if source == output or source in output.parents or output in source.parents:
        raise ValueError("Input and output must be separate.")
    if weights == output or weights in output.parents or output in weights.parents:
        raise ValueError("Weights and output must be separate.")

    images = input_images(source)
    model = load_model(weights)
    results = []
    for image in images:
        try:
            results.append((image, predict_image(model, image)))
        except Exception as error:
            raise RuntimeError(f"Could not classify {image}: {error}") from error

    write_outputs(results, output)
    print(f"Classified {len(results)} image(s). Results: {output / 'predictions.csv'}")


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"ERROR: {error}", file=sys.stderr)
        sys.exit(1)
